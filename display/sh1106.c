static bool cmd(uint8_t c) {
    uint8_t b[2] = {0x00, c};
    return i2c_write_blocking(bus, addr, b, 2, false) == 2;
}

bool sh1106_init(i2c_inst_t *i2c, uint8_t address) {
    bus = i2c; addr = address;
    const uint8_t init[] = {0xae,0xd5,0x80,0xa8,0x3f,0xd3,0x00,0x40,0xad,0x8b,0xa1,0xc8,0xda,0x12,0x81,0x7f,0xd9,0x22,0xdb,0x35,0xa4,0xa6,0xaf};
    for (unsigned i=0;i<sizeof(init);++i) if (!cmd(init[i])) return false;
    sh1106_clear(); sh1106_show();
    return true;
}

void sh1106_clear(void) { memset(fb, 0, sizeof(fb)); }
void sh1106_pixel(int x,int y,bool on) {
    if (x<0||x>=128||y<0||y>=64) return;
    uint8_t *p=&fb[x+(y>>3)*128], m=1u<<(y&7);
    if(on)*p|=m; else *p&=(uint8_t)~m;
}
void sh1106_text(int x,int y,const char *s,uint8_t scale) {
    if (!scale) scale=1;
    while(*s){ unsigned ch=(unsigned char)*s++; if(ch<32||ch>127)ch='?';
        const uint8_t *g=font5x7[ch-32];
        for(int col=0;col<6;col++){uint8_t bits=col<5?g[col]:0; for(int row=0;row<7;row++) if(bits&(1u<<row)) for(int dx=0;dx<scale;dx++)for(int dy=0;dy<scale;dy++)sh1106_pixel(x+col*scale+dx,y+row*scale+dy,true);} x+=6*scale;
    }
}
void sh1106_text_center(int y,const char*s,uint8_t scale){int w=(int)strlen(s)*6*scale;sh1106_text((128-w)/2,y,s,scale);}
void sh1106_show(void) {
    uint8_t packet[129]; packet[0]=0x40;
    for(uint8_t page=0;page<8;page++){
        cmd((uint8_t)(0xb0|page)); cmd(0x02); cmd(0x10);
        memcpy(&packet[1],&fb[page*128],128);
        i2c_write_blocking(bus,addr,packet,sizeof(packet),false);
    }
}
